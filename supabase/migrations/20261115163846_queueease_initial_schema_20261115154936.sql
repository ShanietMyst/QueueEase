-- Only an already-authorized admin can promote/demote another active account.
-- Self-promotion/self-demotion is prohibited; the final active admin cannot be removed.
-- The first administrator must be provisioned by the project owner in SQL Editor
-- after the intended Auth account has signed up; no browser-callable bootstrap exists.
create or replace function public.admin_set_administrator(p_user_id uuid, p_enabled boolean)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_target public.users%rowtype;
  v_admin_count integer;
begin
  if not private.is_queueease_admin() then
    raise exception using errcode = '42501', message = 'Administrator access is required.';
  end if;
  if p_user_id is null or p_enabled is null or p_user_id = auth.uid() then
    raise exception using errcode = '22023', message = 'Choose another account and a valid administrator action.';
  end if;
  perform pg_advisory_xact_lock(749236144);
  select * into v_target from public.users where id = p_user_id for update;
  if not found or not v_target.is_active then
    raise exception using errcode = 'P0002', message = 'An active target account is required.';
  end if;
  if not p_enabled and (v_target.role <> 'admin'
     or not exists (select 1 from public.administrators where id = p_user_id and is_active)) then
    raise exception using errcode = 'P0002', message = 'Administrator account not found.';
  end if;

  if p_enabled then
    update public.users set role = 'admin' where id = p_user_id;
    insert into public.administrators (id, is_active) values (p_user_id, true)
      on conflict (id) do update set is_active = true;
  else
    select count(*) into v_admin_count from public.users u
      join public.administrators a on a.id = u.id
      where u.role = 'admin' and u.is_active and a.is_active;
    if v_admin_count <= 1 then
      raise exception using errcode = '23514', message = 'The last active administrator cannot be removed.';
    end if;
    delete from public.administrators where id = p_user_id;
    update public.users set role = 'user' where id = p_user_id;
  end if;
  perform private.write_activity(auth.uid(), 'administrator',
    case when p_enabled then 'administrator_granted' else 'administrator_revoked' end,
    'user', null, jsonb_build_object('user_id', p_user_id));
end;
$$;

-- Anonymous queue monitoring exposes queue numbers/status only, never appointment
-- identifiers or patient/profile fields. Authenticated users also receive their own
-- current queue summary after an explicit active-user check.
create or replace function public.public_queue_snapshot()
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, public
as $$
declare
  v_today date := private.queueease_today();
  v_uid uuid := auth.uid();
  v_serving text;
  v_waiting jsonb;
  v_your_queue jsonb := null;
  v_mine record;
  v_ahead integer;
begin
  select 'Q-' || lpad(q.queue_number_int::text, 3, '0') into v_serving
    from public.queue_records q
    where q.service_date = v_today and q.service_name = 'General' and q.status = 'Serving'
    order by q.queue_number_int limit 1;

  select coalesce(jsonb_agg(
      jsonb_build_object('queue_number', 'Q-' || lpad(q.queue_number_int::text, 3, '0'))
      order by q.queue_number_int), '[]'::jsonb)
    into v_waiting
    from public.queue_records q
    where q.service_date = v_today and q.service_name = 'General' and q.status = 'Waiting';

  if v_uid is not null and private.is_queueease_active_user() then
    select q.queue_number_int, q.status into v_mine
      from public.queue_records q join public.appointments a on a.id = q.appointment_id
      where a.user_id = v_uid and q.service_date = v_today
        and q.service_name = 'General' and q.status in ('Waiting', 'Serving')
      order by q.queue_number_int limit 1;
    if found then
      select count(*) into v_ahead from public.queue_records q
        where q.service_date = v_today and q.service_name = 'General'
          and q.status = 'Waiting' and q.queue_number_int < v_mine.queue_number_int;
      v_your_queue := jsonb_build_object(
        'queue_number', 'Q-' || lpad(v_mine.queue_number_int::text, 3, '0'),
        'status', v_mine.status,
        'people_ahead', v_ahead
      );
    end if;
  end if;

  return jsonb_build_object(
    'currently_serving', v_serving,
    'waiting', v_waiting,
    'your_queue', v_your_queue,
    'updated_at', now()
  );
end;
$$;

