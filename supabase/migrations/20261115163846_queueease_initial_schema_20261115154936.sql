-- The profile email is Auth-owned; users may edit only their name and phone.
-- Role/active-state changes are available only through admin RPCs below.
create or replace function public.book_appointment(
  p_appointment_date date,
  p_time_slot text,
  p_purpose text,
  p_notes text default ''
)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_uid uuid := auth.uid();
  v_user public.users%rowtype;
  v_schedule public.schedules%rowtype;
  v_count integer;
  v_id bigint;
begin
  if v_uid is null or not private.is_queueease_active_user() then
    raise exception using errcode = '42501', message = 'An active QueueEase user account is required.';
  end if;
  if p_purpose is null or btrim(p_purpose) = '' or char_length(btrim(p_purpose)) > 160 then
    raise exception using errcode = '22023', message = 'Purpose is required and must be at most 160 characters.';
  end if;
  if coalesce(char_length(p_notes), 0) > 1000 then
    raise exception using errcode = '22023', message = 'Notes must be at most 1000 characters.';
  end if;

  select * into v_user from public.users where id = v_uid and role = 'user' and is_active;
  if not found then
    raise exception using errcode = '42501', message = 'Only active user accounts may book appointments.';
  end if;

  if p_appointment_date is null or p_time_slot is null or btrim(p_time_slot) = '' then
    raise exception using errcode = '22023', message = 'Choose a valid appointment date and time slot.';
  end if;
  select * into v_schedule from public.schedules
    where service_date = p_appointment_date and time_slot = btrim(p_time_slot) for update;
  if not found or not v_schedule.is_available or v_schedule.service_date < private.queueease_today() then
    raise exception using errcode = 'P0002', message = 'That appointment time is unavailable.';
  end if;

  select count(*) into v_count from public.appointments
   where schedule_id = v_schedule.id and status in ('Pending', 'Confirmed');
  if v_count >= v_schedule.capacity then
    raise exception using errcode = '23514', message = 'That appointment time has reached capacity.';
  end if;

  insert into public.appointments
    (user_id, schedule_id, full_name, contact_number, email, purpose, notes,
     appointment_date, time_slot, details)
  values
    (v_uid, v_schedule.id, v_user.full_name, v_user.contact_number, v_user.email,
     btrim(p_purpose), coalesce(btrim(p_notes), ''), v_schedule.service_date,
     v_schedule.time_slot, btrim(p_purpose))
  returning id into v_id;

  perform private.write_notification(
    v_uid, 'user', 'appointments', 'Appointment requested',
    'Your appointment request for ' || v_schedule.service_date::text || ' at ' || v_schedule.time_slot || ' is awaiting approval.',
    'appointment-requested-' || v_id::text
  );
  perform private.write_activity(v_uid, 'user', 'appointment_requested', 'appointment', v_id);
  return v_id;
end;
$$;

create or replace function public.cancel_appointment(p_appointment_id bigint)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_uid uuid := auth.uid();
  v_schedule_id bigint;
  v_schedule public.schedules%rowtype;
  v_appointment public.appointments%rowtype;
  v_queue_status text;
begin
  if v_uid is null or not private.is_queueease_active_user() then
    raise exception using errcode = '42501', message = 'An active QueueEase user account is required.';
  end if;
  select schedule_id into v_schedule_id from public.appointments
    where id = p_appointment_id and user_id = v_uid;
  if not found then
    raise exception using errcode = 'P0002', message = 'Appointment not found.';
  end if;

  select * into v_schedule from public.schedules where id = v_schedule_id for update;
  perform private.lock_queue_day(v_schedule.service_date, 'General');
  select * into v_appointment from public.appointments
    where id = p_appointment_id and user_id = v_uid for update;
  if not found then
    raise exception using errcode = 'P0002', message = 'Appointment not found.';
  end if;
  if v_appointment.status not in ('Pending', 'Confirmed') then
    raise exception using errcode = '23514', message = 'This appointment can no longer be cancelled.';
  end if;

  select status into v_queue_status from public.queue_records
    where appointment_id = p_appointment_id for update;
  if v_queue_status = 'Serving' then
    raise exception using errcode = '23514', message = 'An appointment currently being served cannot be cancelled.';
  end if;

  update public.appointments set status = 'Cancelled' where id = p_appointment_id;
  update public.queue_records set status = 'Cancelled'
    where appointment_id = p_appointment_id and status = 'Waiting';
  perform private.write_notification(
    v_uid, 'user', 'appointments', 'Appointment cancelled',
    'Your appointment for ' || v_schedule.service_date::text || ' has been cancelled.',
    'appointment-cancelled-' || p_appointment_id::text
  );
  perform private.write_activity(v_uid, 'user', 'appointment_cancelled', 'appointment', p_appointment_id);
end;
$$;

create or replace function public.admin_decide_appointment(p_appointment_id bigint, p_status text)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_schedule_id bigint;
  v_schedule public.schedules%rowtype;
  v_appointment public.appointments%rowtype;
  v_count integer;
  v_number integer;
  v_queue_id bigint;
  v_queue_text text;
begin
  if not private.is_queueease_admin() then
    raise exception using errcode = '42501', message = 'Administrator access is required.';
  end if;
  if p_status is null or p_status not in ('Confirmed', 'Rejected') then
    raise exception using errcode = '22023', message = 'Decision must be Confirmed or Rejected.';
  end if;
  select schedule_id into v_schedule_id from public.appointments where id = p_appointment_id;
  if not found then
    raise exception using errcode = 'P0002', message = 'Appointment not found.';
  end if;
  select * into v_schedule from public.schedules where id = v_schedule_id for update;
  perform private.lock_queue_day(v_schedule.service_date, 'General');
  select * into v_appointment from public.appointments where id = p_appointment_id for update;
  if not found or v_appointment.status <> 'Pending' then
    raise exception using errcode = '23514', message = 'This request is no longer pending.';
  end if;

  if p_status = 'Confirmed' then
    select count(*) into v_count from public.appointments
      where schedule_id = v_schedule.id and status in ('Pending', 'Confirmed');
    if v_count > v_schedule.capacity then
      raise exception using errcode = '23514', message = 'Schedule capacity is below its active bookings.';
    end if;
    v_number := private.next_queue_number(v_schedule.service_date, 'General');
    v_queue_text := 'Q-' || lpad(v_number::text, 3, '0');
    insert into public.queue_records
      (appointment_id, queue_number, queue_number_int, service_date, service_name, queue_date)
    values
      (p_appointment_id, v_queue_text, v_number, v_schedule.service_date, 'General', v_schedule.service_date)
    returning id into v_queue_id;
  end if;

  update public.appointments set status = p_status where id = p_appointment_id;
  perform private.write_notification(
    v_appointment.user_id, 'user', 'appointments', 'Appointment update',
    case when p_status = 'Confirmed'
      then 'Your appointment for ' || v_appointment.purpose || ' on ' || v_schedule.service_date::text || ' at ' || v_schedule.time_slot || ' has been confirmed.'
      else 'Your appointment for ' || v_appointment.purpose || ' on ' || v_schedule.service_date::text || ' at ' || v_schedule.time_slot || ' was not approved.'
    end,
    'appointment-' || p_appointment_id::text || '-' || lower(p_status)
  );
  perform private.write_activity(auth.uid(), 'administrator', 'appointment_' || lower(p_status), 'appointment', p_appointment_id);
  return jsonb_build_object('appointment_id', p_appointment_id, 'status', p_status,
    'queue_id', v_queue_id, 'queue_number', v_queue_text);
end;
$$;

create or replace function public.admin_upsert_schedule(
  p_service_date date,
  p_time_slot text,
  p_capacity integer,
  p_is_available boolean default true
)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_schedule public.schedules%rowtype;
  v_booked integer;
  v_id bigint;
  v_changed boolean := false;
  v_message text;
  v_user record;
begin
  if not private.is_queueease_admin() then
    raise exception using errcode = '42501', message = 'Administrator access is required.';
  end if;
  if p_service_date is null or p_service_date < private.queueease_today()
     or p_time_slot is null or btrim(p_time_slot) = '' or char_length(btrim(p_time_slot)) > 80
     or p_capacity is null or p_capacity < 1 or p_capacity > 500 or p_is_available is null then
    raise exception using errcode = '22023', message = 'Provide a future/today date, valid time slot, capacity 1â€“500, and availability.';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(
    'queueease-schedule|' || p_service_date::text || '|' || btrim(p_time_slot), 0));
  select * into v_schedule from public.schedules
    where service_date = p_service_date and time_slot = btrim(p_time_slot) for update;
  if found then
    select count(*) into v_booked from public.appointments
      where schedule_id = v_schedule.id and status in ('Pending', 'Confirmed');
    if p_capacity < v_booked then
      raise exception using errcode = '23514', message = 'Capacity cannot be lower than active bookings.';
    end if;
    v_changed := v_schedule.capacity <> p_capacity or v_schedule.is_available <> p_is_available;
    update public.schedules set capacity = p_capacity, is_available = p_is_available
      where id = v_schedule.id returning id into v_id;
    if v_changed then
      v_message := case when p_is_available
        then 'The schedule for ' || p_service_date::text || ' at ' || btrim(p_time_slot) || ' was updated.'
        else 'The schedule for ' || p_service_date::text || ' at ' || btrim(p_time_slot) || ' is now unavailable. Contact the clinic about your appointment.'
      end;
      for v_user in
        select distinct user_id from public.appointments
          where schedule_id = v_id and user_id is not null and status in ('Pending', 'Confirmed')
      loop
        perform private.write_notification(v_user.user_id, 'user', 'appointments', 'Schedule update', v_message,
          'schedule-update-' || v_id::text || '-' || p_capacity::text || '-' || p_is_available::text || '-' || v_user.user_id::text);
      end loop;
    end if;
  else
    insert into public.schedules (service_date, time_slot, capacity, is_available)
      values (p_service_date, btrim(p_time_slot), p_capacity, p_is_available)
      returning id into v_id;
  end if;
  perform private.write_activity(auth.uid(), 'administrator', 'schedule_saved', 'schedule', v_id);
  return v_id;
end;
