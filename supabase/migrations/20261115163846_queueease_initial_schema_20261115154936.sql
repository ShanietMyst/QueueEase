create or replace function public.admin_set_queue_status(p_queue_id bigint, p_status text)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_record public.queue_records%rowtype;
  v_user_id uuid;
  v_next record;
begin
  if not private.is_queueease_admin() then
    raise exception using errcode = '42501', message = 'Administrator access is required.';
  end if;
  if p_status is null or p_status not in ('Serving', 'Completed', 'Skipped', 'Cancelled') then
    raise exception using errcode = '22023', message = 'Unsupported queue status.';
  end if;
  select * into v_record from public.queue_records where id = p_queue_id;
  if not found then
    raise exception using errcode = 'P0002', message = 'Queue record not found.';
  end if;
  perform private.lock_queue_day(v_record.service_date, v_record.service_name);
  select * into v_record from public.queue_records where id = p_queue_id for update;
  if (v_record.status = 'Waiting' and p_status not in ('Serving', 'Skipped', 'Cancelled'))
     or (v_record.status = 'Serving' and p_status not in ('Completed', 'Skipped', 'Cancelled')) then
    raise exception using errcode = '23514', message = 'This queue record cannot make that status transition.';
  end if;
  if p_status = 'Serving' and exists (
    select 1 from public.queue_records q where q.service_date = v_record.service_date
      and q.service_name = v_record.service_name and q.status = 'Serving' and q.id <> v_record.id
  ) then
    raise exception using errcode = '23514', message = 'Complete or skip the current number before calling another.';
  end if;

  update public.queue_records set status = p_status where id = p_queue_id;
  if p_status = 'Completed' then
    update public.appointments set status = 'Completed' where id = v_record.appointment_id;
  elsif p_status = 'Cancelled' then
    update public.appointments set status = 'Cancelled' where id = v_record.appointment_id;
  end if;
  select user_id into v_user_id from public.appointments where id = v_record.appointment_id;
  if v_user_id is not null then
    perform private.write_notification(v_user_id, 'user', 'queue_updates', 'Queue status update',
      case when p_status = 'Completed'
        then 'Your queue number ' || v_record.queue_number || ' has been completed.'
        when p_status = 'Skipped'
        then 'Your queue number ' || v_record.queue_number || ' was skipped. Please ask staff for assistance.'
        else 'Your queue number ' || v_record.queue_number || ' is now ' || lower(p_status) || '.'
      end,
      'queue-status-' || p_queue_id::text || '-' || lower(p_status));
  end if;
  if p_status = 'Serving' then
    select q.id, q.queue_number into v_next from public.queue_records q
      where q.service_date = v_record.service_date and q.service_name = v_record.service_name
        and q.status = 'Waiting' order by q.queue_number_int limit 1;
    if found then
      select a.user_id into v_user_id from public.appointments a
        join public.queue_records q on q.appointment_id = a.id where q.id = v_next.id;
      if v_user_id is not null then
        perform private.write_notification(v_user_id, 'user', 'queue_updates', 'Your turn is coming soon',
          'The clinic is serving ' || v_record.queue_number || '. Your queue number ' || v_next.queue_number || ' is next; please be ready.',
          'queue-approaching-after-' || p_queue_id::text || '-for-' || v_next.id::text);
      end if;
    end if;
  end if;
  perform private.write_activity(auth.uid(), 'administrator', 'queue_' || lower(p_status), 'queue_record', p_queue_id);
end;
$$;

