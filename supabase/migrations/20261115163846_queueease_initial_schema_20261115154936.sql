-- Auth email signup is required by QueueEase. Reject missing/oversized email
-- rather than creating blank or unusable public profile identities.
create or replace function public.validate_queueease_auth_email()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  -- Supabase anonymous users intentionally have no email; they get no QueueEase
  -- profile and cannot use authenticated QueueEase data operations.
  if new.is_anonymous then
    return new;
  end if;
  if new.email is null or btrim(new.email) = '' or char_length(new.email) > 190 then
    raise exception using
      errcode = '22023',
      message = 'QueueEase accounts require a valid email address of at most 190 characters.';
  end if;
  new.email := lower(btrim(new.email));
  return new;
end;
$$;
revoke all on function public.validate_queueease_auth_email() from public, anon, authenticated;

create trigger queueease_auth_email_required_insert
  before insert on auth.users
  for each row execute function public.validate_queueease_auth_email();
create trigger queueease_auth_email_required_update
  before update of email on auth.users
  for each row execute function public.validate_queueease_auth_email();

create or replace function public.handle_queueease_auth_user_created()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_full_name text;
  v_contact_number text;
begin
  if new.is_anonymous then
    return new;
  end if;
  -- Normal QueueEase signups must supply both profile fields. Metadata is
  -- untrusted client input: trim/collapse whitespace, reject controls and
  -- enforce bounds before creating the private profile. Anonymous Auth users
  -- intentionally return above without a QueueEase student profile.
  v_full_name := regexp_replace(btrim(coalesce(new.raw_user_meta_data ->> 'full_name', '')), '[[:space:]]+', ' ', 'g');
  v_contact_number := regexp_replace(btrim(coalesce(new.raw_user_meta_data ->> 'contact_number', '')), '[[:space:]]+', ' ', 'g');
  if v_full_name = '' or char_length(v_full_name) > 120
     or v_full_name ~ '[[:cntrl:]]'
     or v_contact_number = '' or char_length(v_contact_number) > 30
     or v_contact_number !~ '^[+0-9() .-]+$' then
    raise exception using errcode = '22023',
      message = 'QueueEase registration requires a valid full name and mobile number.';
  end if;
  insert into public.users (id, full_name, email, contact_number)
  values (
    new.id,
    v_full_name,
    new.email,
    v_contact_number
  );
  return new;
end;
$$;
revoke all on function public.handle_queueease_auth_user_created() from public, anon, authenticated;
create trigger on_auth_user_created_queueease
  after insert on auth.users
  for each row execute function public.handle_queueease_auth_user_created();

