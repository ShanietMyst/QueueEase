-- A hard Auth deletion first anonymizes appointment snapshots and detaches the
-- records. Appointments and queue history remain; notification content is removed.
-- Admin identities must be demoted through trusted admin management first.
create or replace function public.preserve_queueease_history_before_user_delete()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.role = 'admin' then
    raise exception using errcode = '23514',
      message = 'Demote this administrator through a second active administrator before deleting the account.';
  end if;

  update public.queue_records q
     set status = 'Cancelled'
   where q.status in ('Waiting', 'Serving')
     and exists (
       select 1 from public.appointments a
       where a.id = q.appointment_id and a.user_id = old.id
     );

  update public.appointments
     set user_id = null,
         full_name = 'Deleted account',
         contact_number = '',
         email = 'deleted-' || replace(old.id::text, '-', '') || '@invalid.example',
         purpose = 'Account removed',
         notes = '',
         details = null,
         status = case when status in ('Pending', 'Confirmed') then 'Cancelled' else status end
   where user_id = old.id;

  delete from public.notifications where user_id = old.id;
  update public.activity_logs set actor_id = null where actor_id = old.id;
  return old;
end;
$$;
revoke all on function public.preserve_queueease_history_before_user_delete() from public, anon, authenticated;
create trigger preserve_queueease_history_on_user_delete
  before delete on public.users
  for each row execute function public.preserve_queueease_history_before_user_delete();

