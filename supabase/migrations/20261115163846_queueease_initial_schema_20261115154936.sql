-- QueueEase PostgreSQL schema preparation.
-- Review before applying. This migration has NOT been run against Supabase.
-- Auth identities live in auth.users. This file creates profiles and app tables only;
-- it does not import MySQL rows or password hashes.

begin;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
grant usage on schema private to authenticated;

-- User identifiers are Auth UUIDs. A role value alone is insufficient for admin
-- authorization: an active row in administrators is also required.
create table public.users (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name varchar(150) not null,
  email varchar(190) not null unique,
  contact_number varchar(30) not null,
  role text not null default 'user' check (role in ('user', 'admin')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.administrators (
  id uuid primary key references public.users (id) on delete cascade,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.schedules (
  id bigint generated by default as identity primary key,
  service_date date not null,
  time_slot varchar(80) not null,
  capacity integer not null check (capacity between 1 and 500),
  is_available boolean not null default true,
  schedule_date date,
  start_time time,
  end_time time,
  created_at timestamptz not null default now(),
  constraint uq_schedules_date_slot unique (service_date, time_slot)
);
create index idx_schedules_available_date on public.schedules (is_available, service_date);

create table public.appointments (
  id bigint generated by default as identity primary key,
  user_id uuid references public.users (id) on delete set null,
  schedule_id bigint not null references public.schedules (id),
  full_name varchar(150) not null,
  contact_number varchar(30) not null default '',
  email varchar(190) not null,
  purpose text not null,
  notes varchar(1000) not null default '',
  appointment_date date,
  time_slot varchar(50),
  details text,
  status text not null default 'Pending'
    check (status in ('Pending', 'Confirmed', 'Rejected', 'Completed', 'Cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index idx_appointments_user_date on public.appointments (user_id, created_at);
create index idx_appointments_schedule_status on public.appointments (schedule_id, status);

create table public.queue_records (
  id bigint generated by default as identity primary key,
  appointment_id bigint not null unique references public.appointments (id),
  queue_number varchar(20) not null,
  queue_number_int integer not null check (queue_number_int >= 0),
  service_date date not null,
  service_name varchar(80) not null default 'General',
  queue_date date,
  status text not null default 'Waiting'
    check (status in ('Waiting', 'Serving', 'Completed', 'Skipped', 'Cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint uq_queue_daily_number unique (service_date, service_name, queue_number_int)
);
create index idx_queue_order
  on public.queue_records (service_date, service_name, status, queue_number_int);
create index idx_queue_legacy_number on public.queue_records (queue_number);

create table public.activity_logs (
  id bigint generated by default as identity primary key,
  actor_type text not null check (actor_type in ('user', 'administrator', 'system')),
  actor_id uuid,
  action varchar(80) not null,
  entity_type varchar(40) not null,
  entity_id bigint,
  details jsonb,
  created_at timestamptz not null default now()
);
create index idx_activity_created on public.activity_logs (created_at);
create index idx_activity_entity on public.activity_logs (entity_type, entity_id);

create table public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid references public.users (id) on delete set null,
  recipient_role text not null default 'user' check (recipient_role in ('user', 'admin')),
  category text not null default 'system'
    check (category in ('appointments', 'queue_updates', 'announcements', 'system')),
  title varchar(120) not null,
  message text not null,
  event_key varchar(190) unique,
  is_read boolean not null default false,
  created_at timestamptz not null default now(),
  constraint notifications_recipient_check
    check ((recipient_role = 'user' and user_id is not null)
        or (recipient_role = 'admin' and user_id is not null))
);
create index idx_notifications_recipient_read
  on public.notifications (recipient_role, user_id, is_read, created_at);

create table public.system_settings (
  id integer generated by default as identity primary key,
  setting_name varchar(100) not null unique,
  setting_value varchar(255) not null default ''
);

-- These helpers are outside the exposed public API schema. Fixed search paths and
-- narrowly granted execution prevent caller-controlled name resolution.
create or replace function private.is_queueease_admin()
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select exists (
    select 1
    from public.users u
    join public.administrators a on a.id = u.id
    where u.id = auth.uid()
      and u.role = 'admin'
      and u.is_active
      and a.is_active
  );
$$;
revoke all on function private.is_queueease_admin() from public, anon;
grant execute on function private.is_queueease_admin() to authenticated;

create or replace function private.is_queueease_active_user()
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select exists (
    select 1 from public.users u
    where u.id = auth.uid() and u.role = 'user' and u.is_active
  );
$$;
revoke all on function private.is_queueease_active_user() from public, anon;
grant execute on function private.is_queueease_active_user() to authenticated;

create or replace function private.queueease_today()
returns date
language sql
stable
set search_path = pg_catalog
as $$
  select timezone('Asia/Taipei', now())::date;
$$;
revoke all on function private.queueease_today() from public, anon, authenticated;

create or replace function private.lock_queue_day(p_service_date date, p_service_name text)
returns void
language sql
volatile
set search_path = pg_catalog
as $$
  select pg_advisory_xact_lock(
    hashtextextended('queueease|' || p_service_date::text || '|' || p_service_name, 0)
  );
$$;
revoke all on function private.lock_queue_day(date, text) from public, anon, authenticated;

create or replace function private.next_queue_number(p_service_date date, p_service_name text)
returns integer
language plpgsql
volatile
set search_path = pg_catalog, public
as $$
declare
  v_next integer;
begin
  perform private.lock_queue_day(p_service_date, p_service_name);
  select coalesce(max(q.queue_number_int), 0) + 1
    into v_next
    from public.queue_records q
    where q.service_date = p_service_date and q.service_name = p_service_name;
  return v_next;
end;
$$;
revoke all on function private.next_queue_number(date, text) from public, anon, authenticated;

