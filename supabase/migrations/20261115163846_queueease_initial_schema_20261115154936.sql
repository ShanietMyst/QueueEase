create or replace function public.admin_advance_queue()
returns text
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_today date := private.queueease_today();
  v_current public.queue_records%rowtype;
  v_next public.queue_records%rowtype;
  v_following_id bigint;
  v_following_number text;
  v_user_id uuid;
begin
  if not private.is_queueease_admin() then
    raise exception using errcode = '42501', message = 'Administrator access is required.';
  end if;
  perform private.lock_queue_day(v_today, 'General');

  select * into v_current from public.queue_records
    where service_date = v_today and service_name = 'General' and status = 'Serving'
    order by queue_number_int limit 1 for update;
  if found then
    update public.queue_records set status = 'Completed' where id = v_current.id;
    update public.appointments set status = 'Completed' where id = v_current.appointment_id;
    select user_id into v_user_id from public.appointments where id = v_current.appointment_id;
    if v_user_id is not null then
      perform private.write_notification(v_user_id, 'user', 'queue_updates', 'Queue visit completed',
        'Your queue number ' || v_current.queue_number || ' has been completed.',
        'queue-status-' || v_current.id::text || '-completed');
    end if;
    perform private.write_activity(auth.uid(), 'administrator', 'queue_completed', 'queue_record', v_current.id);
  end if;

  select * into v_next from public.queue_records
    where service_date = v_today and service_name = 'General' and status = 'Waiting'
    order by queue_number_int limit 1 for update;
  if not found then
    return null;
  end if;
  update public.queue_records set status = 'Serving' where id = v_next.id;
  select user_id into v_user_id from public.appointments where id = v_next.appointment_id;
  if v_user_id is not null then
    perform private.write_notification(v_user_id, 'user', 'queue_updates', 'Your turn is now',
      'Your queue number ' || v_next.queue_number || ' is now being served.',
      'queue-serving-' || v_next.id::text);
  end if;

  select q.id, q.queue_number into v_following_id, v_following_number from public.queue_records q
    where q.service_date = v_today and q.service_name = 'General' and q.status = 'Waiting'
    order by q.queue_number_int limit 1;
  if found then
    select a.user_id into v_user_id from public.appointments a
      join public.queue_records q on q.appointment_id = a.id
      where q.id = v_following_id;
    if v_user_id is not null then
      perform private.write_notification(v_user_id, 'user', 'queue_updates', 'Your turn is coming soon',
        'The clinic is serving ' || v_next.queue_number || '. Your queue number ' || v_following_number || ' is next; please be ready.',
        'queue-approaching-after-' || v_next.id::text || '-for-' || v_following_id::text);
    end if;
  end if;
  perform private.write_activity(auth.uid(), 'administrator', 'queue_called', 'queue_record', v_next.id);
  return v_next.queue_number;
end;
$$;

create or replace function public.admin_publish_announcement(p_title text, p_message text)
returns integer
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_user record;
  v_count integer := 0;
  v_event text;
begin
  if not private.is_queueease_admin() then
    raise exception using errcode = '42501', message = 'Administrator access is required.';
  end if;
  if p_title is null or btrim(p_title) = '' or char_length(btrim(p_title)) > 120
     or p_message is null or btrim(p_message) = '' or char_length(btrim(p_message)) > 3000 then
    raise exception using errcode = '22023', message = 'Title and announcement are required and must fit their length limits.';
  end if;
  v_event := 'announcement-' || gen_random_uuid()::text;
  for v_user in select id from public.users where role = 'user' and is_active loop
    perform private.write_notification(v_user.id, 'user', 'announcements', btrim(p_title), btrim(p_message),
      v_event || '-user-' || v_user.id::text);
    v_count := v_count + 1;
  end loop;
  perform private.write_activity(auth.uid(), 'administrator', 'announcement_published', 'announcement', null,
    jsonb_build_object('title', btrim(p_title), 'recipient_count', v_count));
  return v_count;
end;
$$;

create or replace function public.admin_set_user_active(p_user_id uuid, p_is_active boolean)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_updated uuid;
begin
  if not private.is_queueease_admin() then
    raise exception using errcode = '42501', message = 'Administrator access is required.';
  end if;
